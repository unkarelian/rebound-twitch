#!/usr/bin/env node
// Builds the extension for Firefox (MV2) and Chrome (MV3).
//
//   node extension/build.js [--target firefox|chrome|all] [--out DIR]
//                           [--defaults config.json] [--no-remote] [--monitor]
//
// --defaults   bundle this config instead of config/defaults.json. The monitor
//              and fixers use it to live-test a candidate config before signing.
// --no-remote  never fetch remote config (candidate/regression builds).
// --monitor    turn on vaft's monitor instrumentation (twitchAdSolutions_monitor).
'use strict';
const fs = require('fs');
const path = require('path');
const { validateConfig } = require('./src/shared/config.js');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(__dirname, 'src');
const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));

function arg(name, def) {
    const i = process.argv.indexOf(name);
    return i !== -1 ? process.argv[i + 1] : def;
}
const flag = (name) => process.argv.includes(name);

const target = arg('--target', 'all');
const outRoot = path.resolve(arg('--out', path.join(__dirname, 'dist')));
const defaultsPath = path.resolve(arg('--defaults', path.join(ROOT, 'config/defaults.json')));
const remote = !flag('--no-remote');
const monitor = flag('--monitor');

const defaults = JSON.parse(fs.readFileSync(defaultsPath, 'utf8'));
const v = validateConfig(defaults);
if (!v.ok) {
    console.error('bundled defaults are invalid:\n  ' + v.errors.join('\n  '));
    process.exit(1);
}

// The vaft core, unchanged except for dropping the userscript header block.
const vaftSrc = fs.readFileSync(path.join(ROOT, 'vaft/vaft.user.js'), 'utf8').replace(/^\/\/ ==UserScript==[\s\S]*?\/\/ ==\/UserScript==\n/, '');
const vaftVersion = (fs.readFileSync(path.join(ROOT, 'vaft/vaft.user.js'), 'utf8').match(/@version\s+(\S+)/) || [])[1];

function copyDir(from, to) {
    fs.mkdirSync(to, { recursive: true });
    for (const e of fs.readdirSync(from, { withFileTypes: true })) {
        const a = path.join(from, e.name), b = path.join(to, e.name);
        if (e.isDirectory()) copyDir(a, b); else fs.copyFileSync(a, b);
    }
}

function constantsSrc() {
    return fs.readFileSync(path.join(SRC, 'shared/constants.js'), 'utf8')
        .replace(/REMOTE_ENABLED: (true|false), \/\* @build:REMOTE_ENABLED \*\//, `REMOTE_ENABLED: ${remote}, /* @build:REMOTE_ENABLED */`)
        .replace(/MONITOR_MODE: (true|false), \/\* @build:MONITOR_MODE \*\//, `MONITOR_MODE: ${monitor}, /* @build:MONITOR_MODE */`);
}

const ICONS = { 16: 'icons/icon-16.png', 32: 'icons/icon-32.png', 48: 'icons/icon-48.png', 128: 'icons/icon-128.png' };
const DESCRIPTION = 'Blocks Twitch video ads and repairs itself quickly when Twitch changes. Open source, no telemetry. Not affiliated with Twitch.';

function manifest(t) {
    const base = {
        name: 'Rebound for Twitch',
        short_name: 'Rebound',
        version: pkg.version,
        description: DESCRIPTION,
        homepage_url: 'https://github.com/unkarelian/rebound-twitch',
        icons: ICONS,
    };
    if (t === 'firefox') {
        return {
            manifest_version: 2,
            ...base,
            browser_specific_settings: {
                gecko: {
                    id: 'rebound-twitch@unkarelian.github.io',
                    strict_min_version: '140.0', // Ed25519 WebCrypto (129+); data_collection_permissions (140+, ESR)
                    data_collection_permissions: { required: ['none'] },
                },
                gecko_android: { strict_min_version: '142.0' },
            },
            permissions: ['storage', 'alarms', 'tabs', '*://*.twitch.tv/*', 'https://raw.githubusercontent.com/*'],
            background: { scripts: ['shared/config.js', 'shared/keys.js', 'shared/constants.js', 'shared/defaults.js', 'background.js'], persistent: true },
            browser_action: { default_popup: 'popup/popup.html', default_icon: ICONS, default_title: 'Rebound for Twitch' },
        };
    }
    return {
        manifest_version: 3,
        ...base,
        minimum_chrome_version: '137', // Ed25519 in WebCrypto
        permissions: ['storage', 'alarms', 'scripting', 'tabs'],
        host_permissions: ['*://*.twitch.tv/*', 'https://raw.githubusercontent.com/*'],
        background: { service_worker: 'background.js' },
        action: { default_popup: 'popup/popup.html', default_icon: ICONS, default_title: 'Rebound for Twitch' },
    };
}

function build(t) {
    const out = path.join(outRoot, t);
    fs.rmSync(out, { recursive: true, force: true });
    copyDir(SRC, out);
    copyDir(path.join(__dirname, 'icons'), path.join(out, 'icons'));
    fs.writeFileSync(path.join(out, 'shared/constants.js'), constantsSrc());
    fs.writeFileSync(path.join(out, 'shared/defaults.js'), '// Generated by build.js from ' + path.relative(ROOT, defaultsPath) + '\nglobalThis.REBOUND_BUNDLED_DEFAULTS = ' + JSON.stringify(defaults) + ';\n');
    const header = `// Rebound for Twitch ${pkg.version}: vaft ${vaftVersion} core from TwitchAdSolutions (MIT, TwitchAdSolutions Contributors).\n`;
    const contentSrc = fs.readFileSync(path.join(SRC, 'content.js'), 'utf8');
    if (t === 'firefox') {
        // Page script travels inside the content script as a string and is injected
        // inline at document_start (twitch.tv sends no CSP). See docs/DECISIONS.md.
        fs.writeFileSync(path.join(out, 'content.js'), header + 'const REBOUND_PAGE_SRC = ' + JSON.stringify(vaftSrc) + ';\n' + contentSrc);
    } else {
        fs.mkdirSync(path.join(out, 'page'), { recursive: true });
        fs.writeFileSync(path.join(out, 'page/vaft.js'), header + vaftSrc);
        fs.writeFileSync(path.join(out, 'page/boot.js'), '// MAIN world, runs before vaft.js. Bundled defaults; the relay posts newer signed config.\n' +
            (monitor ? "try { localStorage.setItem('twitchAdSolutions_monitor', 'true'); } catch {}\n" : '') +
            'window.__reboundRemoteConfig = ' + JSON.stringify(defaults) + ';\n');
        fs.writeFileSync(path.join(out, 'content.js'), contentSrc);
    }
    fs.writeFileSync(path.join(out, 'manifest.json'), JSON.stringify(manifest(t), null, 2) + '\n');
    console.log(`built ${t} -> ${path.relative(process.cwd(), out) || out} (config v${defaults.version}${remote ? '' : ', no-remote'}${monitor ? ', monitor' : ''})`);
}

for (const t of target === 'all' ? ['firefox', 'chrome'] : [target]) build(t);
